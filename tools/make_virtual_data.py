def mojibake(s):  # Instagram stores UTF-8 bytes as latin-1 code points
    return s.encode("utf-8").decode("latin-1")


def build():
    posts = []
    for i, (at, caption) in enumerate(POSTS):
        ts = int(datetime.strptime(at, "%Y-%m-%d %H:%M").replace(tzinfo=KST).timestamp())
        media = [{"uri": f"media/posts/202603/virtual_{i:02d}.jpg", "creation_timestamp": ts, "title": ""}]
        if i % 3 == 0:  # single-photo posts keep the caption inside media[0], like the real export
            media[0]["title"] = mojibake(caption)
            posts.append({"media": media})
        else:
            posts.append({"media": media, "title": mojibake(caption), "creation_timestamp": ts})
    OUT.mkdir(parents=True, exist_ok=True)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("your_instagram_activity/media/posts_1.json", json.dumps(posts, indent=2))
    (OUT / "instagram-virtual-haneul.zip").write_bytes(buf.getvalue())
    (OUT / "expected.json").write_text(json.dumps(EXPECTED, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"{len(POSTS)} posts -> {OUT}")


if __name__ == "__main__":
    build()
