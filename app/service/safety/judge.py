"""
app/service/safety/judge.py

사람 판정 문장 검사(1차 gates.judged 옮김). 말 걸기(WS7)가 내보내기 전에 부른다.
"""

import re

JUDGE = re.compile(
    r"(너는|넌|당신은|글쓴이는|작성자는|이 사람은)[^.。!?]{0,30}(사람|애|인간|타입|성격|부류|스타일)"
    r"(이다|입니다|이야|야|이네|이에요|이군|이지|이잖아|잖아|이구나|임)"
    r"|(우울|불안|공황|강박|조울|성격|인격|애착|섭식|적응) ?(증|장애)|ADHD"
    r"|문제가 있는 사람|의지가 약한 사람|게으른 사람|글러 먹었|넌 글렀"
)


def judged(text):
    """사람을 판정 · 진단하는 문장이면 True."""
    return bool(JUDGE.search(text or ""))
